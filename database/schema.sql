-- ----------------------------------------------------------------------------
-- 1. DROP EXISTING CONSTRAINTS AND TABLES (CLEAN SLATE)
-- ----------------------------------------------------------------------------
BEGIN
    FOR cur_rec IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'AUDIT_LOGS', 'UTILIZATION_REPORTS', 'GRANT_DISBURSEMENTS',
        'APPROVAL_WORKFLOW_LOGS', 'APPLICATION_REVIEWS', 'APPLICATION_DOCUMENTS',
        'APPLICATIONS', 'PROGRAM_ELIGIBILITY_CRITERIA', 'GRANT_PROGRAMS',
        'USERS', 'ROLES'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || cur_rec.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 2. MASTER TABLE: ROLES
-- ----------------------------------------------------------------------------
CREATE TABLE ROLES (
    role_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name       VARCHAR2(50) NOT NULL CONSTRAINT uq_role_name UNIQUE,
    display_name    VARCHAR2(100) NOT NULL,
    description     VARCHAR2(300),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 3. MASTER TABLE: USERS
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    user_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR2(50) NOT NULL CONSTRAINT uq_username UNIQUE,
    password_hash       VARCHAR2(255) NOT NULL,
    full_name           VARCHAR2(150) NOT NULL,
    email               VARCHAR2(150) NOT NULL CONSTRAINT uq_user_email UNIQUE,
    phone_number        VARCHAR2(20),
    organization_name   VARCHAR2(200),
    designation         VARCHAR2(100),
    role_id             NUMBER NOT NULL,
    status              VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL 
                        CONSTRAINT chk_user_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED')),
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES ROLES(role_id)
);

CREATE INDEX idx_users_role_id ON USERS(role_id);
CREATE INDEX idx_users_status ON USERS(status);
CREATE INDEX idx_users_email ON USERS(email);

-- ----------------------------------------------------------------------------
-- 4. MASTER TABLE: GRANT_PROGRAMS
-- ----------------------------------------------------------------------------
CREATE TABLE GRANT_PROGRAMS (
    program_id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_code                VARCHAR2(40) NOT NULL CONSTRAINT uq_program_code UNIQUE,
    title                       VARCHAR2(255) NOT NULL,
    category                    VARCHAR2(100) NOT NULL,
    funding_agency              VARCHAR2(200) NOT NULL,
    description                 VARCHAR2(4000),
    total_budget                NUMBER(15,2) NOT NULL CONSTRAINT chk_prog_budget CHECK (total_budget > 0),
    disbursed_budget            NUMBER(15,2) DEFAULT 0.00 NOT NULL CONSTRAINT chk_prog_disb CHECK (disbursed_budget >= 0),
    min_grant_amount            NUMBER(14,2) NOT NULL,
    max_grant_amount            NUMBER(14,2) NOT NULL,
    start_date                  DATE NOT NULL,
    end_date                    DATE NOT NULL,
    status                      VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL 
                                CONSTRAINT chk_prog_status CHECK (status IN ('DRAFT', 'ACTIVE', 'UNDER_EVALUATION', 'CLOSED', 'ARCHIVED')),
    eligibility_summary         VARCHAR2(2000),
    created_by                  NUMBER NOT NULL,
    created_at                  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at                  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_program_creator FOREIGN KEY (created_by) REFERENCES USERS(user_id),
    CONSTRAINT chk_prog_dates CHECK (end_date >= start_date),
    CONSTRAINT chk_prog_grant_range CHECK (max_grant_amount >= min_grant_amount)
);

CREATE INDEX idx_grant_prog_status ON GRANT_PROGRAMS(status);
CREATE INDEX idx_grant_prog_category ON GRANT_PROGRAMS(category);
CREATE INDEX idx_grant_prog_agency ON GRANT_PROGRAMS(funding_agency);
CREATE INDEX idx_grant_prog_dates ON GRANT_PROGRAMS(start_date, end_date);

-- ----------------------------------------------------------------------------
-- 5. DETAIL TABLE: PROGRAM_ELIGIBILITY_CRITERIA
-- ----------------------------------------------------------------------------
CREATE TABLE PROGRAM_ELIGIBILITY_CRITERIA (
    criterion_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id          NUMBER NOT NULL,
    criterion_code      VARCHAR2(50) NOT NULL,
    criterion_name      VARCHAR2(200) NOT NULL,
    criterion_type      VARCHAR2(30) NOT NULL 
                        CONSTRAINT chk_crit_type CHECK (criterion_type IN ('NUMERIC_MIN', 'NUMERIC_MAX', 'TEXT_EQUAL', 'BOOLEAN', 'IN_LIST')),
    expected_value      VARCHAR2(255) NOT NULL,
    is_mandatory        CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT chk_crit_mandatory CHECK (is_mandatory IN ('Y', 'N')),
    weightage           NUMBER(3) DEFAULT 10 NOT NULL,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_crit_program FOREIGN KEY (program_id) REFERENCES GRANT_PROGRAMS(program_id) ON DELETE CASCADE,
    CONSTRAINT uq_prog_crit_code UNIQUE (program_id, criterion_code)
);

CREATE INDEX idx_crit_program_id ON PROGRAM_ELIGIBILITY_CRITERIA(program_id);

-- ----------------------------------------------------------------------------
-- 6. TRANSACTION TABLE: APPLICATIONS
-- ----------------------------------------------------------------------------
CREATE TABLE APPLICATIONS (
    application_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_number          VARCHAR2(50) NOT NULL CONSTRAINT uq_app_number UNIQUE,
    program_id                  NUMBER NOT NULL,
    applicant_id                NUMBER NOT NULL,
    project_title               VARCHAR2(255) NOT NULL,
    project_summary             VARCHAR2(4000) NOT NULL,
    requested_amount            NUMBER(14,2) NOT NULL CONSTRAINT chk_app_requested_amt CHECK (requested_amount > 0),
    approved_amount             NUMBER(14,2) DEFAULT NULL,
    project_duration_months     NUMBER(3) NOT NULL CONSTRAINT chk_app_duration CHECK (project_duration_months > 0),
    target_beneficiaries        VARCHAR2(255),
    state_or_region             VARCHAR2(100) NOT NULL,
    district                    VARCHAR2(100) NOT NULL,
    organization_type           VARCHAR2(100) NOT NULL,
    organization_pan            VARCHAR2(20) NOT NULL,
    organization_gstin          VARCHAR2(20),
    annual_turnover             NUMBER(14,2) DEFAULT 0.00 NOT NULL,
    years_in_operation          NUMBER(3) DEFAULT 0 NOT NULL,
    eligibility_status          VARCHAR2(30) DEFAULT 'CHECK_PENDING' NOT NULL 
                                CONSTRAINT chk_app_elig_status CHECK (eligibility_status IN ('CHECK_PENDING', 'AUTO_ELIGIBLE', 'AUTO_INELIGIBLE', 'OVERRIDDEN_ELIGIBLE')),
    eligibility_remarks         VARCHAR2(1000),
    submission_date             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    status                      VARCHAR2(30) DEFAULT 'SUBMITTED' NOT NULL 
                                CONSTRAINT chk_app_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED', 'DISBURSED', 'COMPLETED')),
    created_at                  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at                  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_app_program FOREIGN KEY (program_id) REFERENCES GRANT_PROGRAMS(program_id),
    CONSTRAINT fk_app_applicant FOREIGN KEY (applicant_id) REFERENCES USERS(user_id)
);

CREATE INDEX idx_app_program_id ON APPLICATIONS(program_id);
CREATE INDEX idx_app_applicant_id ON APPLICATIONS(applicant_id);
CREATE INDEX idx_app_status ON APPLICATIONS(status);
CREATE INDEX idx_app_elig_status ON APPLICATIONS(eligibility_status);
CREATE INDEX idx_app_submission_date ON APPLICATIONS(submission_date);

-- ----------------------------------------------------------------------------
-- 7. DETAIL TABLE: APPLICATION_DOCUMENTS
-- ----------------------------------------------------------------------------
CREATE TABLE APPLICATION_DOCUMENTS (
    document_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      NUMBER NOT NULL,
    document_type       VARCHAR2(50) NOT NULL,
    file_name           VARCHAR2(255) NOT NULL,
    file_path           VARCHAR2(500) NOT NULL,
    file_size_kb        NUMBER(10) NOT NULL,
    content_type        VARCHAR2(100) NOT NULL,
    uploaded_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_doc_application FOREIGN KEY (application_id) REFERENCES APPLICATIONS(application_id) ON DELETE CASCADE
);

CREATE INDEX idx_doc_application_id ON APPLICATION_DOCUMENTS(application_id);

-- ----------------------------------------------------------------------------
-- 8. TRANSACTION TABLE: APPLICATION_REVIEWS
-- ----------------------------------------------------------------------------
CREATE TABLE APPLICATION_REVIEWS (
    review_id                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id              NUMBER NOT NULL,
    reviewer_id                 NUMBER NOT NULL,
    feasibility_score           NUMBER(3) DEFAULT 0 NOT NULL CONSTRAINT chk_rev_feasibility CHECK (feasibility_score BETWEEN 0 AND 25),
    innovation_score            NUMBER(3) DEFAULT 0 NOT NULL CONSTRAINT chk_rev_innovation CHECK (innovation_score BETWEEN 0 AND 25),
    budget_realism_score        NUMBER(3) DEFAULT 0 NOT NULL CONSTRAINT chk_rev_budget CHECK (budget_realism_score BETWEEN 0 AND 25),
    social_impact_score         NUMBER(3) DEFAULT 0 NOT NULL CONSTRAINT chk_rev_social CHECK (social_impact_score BETWEEN 0 AND 25),
    total_score                 NUMBER(3) GENERATED ALWAYS AS (feasibility_score + innovation_score + budget_realism_score + social_impact_score),
    recommendation              VARCHAR2(30) DEFAULT 'RECOMMEND_APPROVE' NOT NULL 
                                CONSTRAINT chk_rev_recom CHECK (recommendation IN ('RECOMMEND_APPROVE', 'RECOMMEND_REJECT', 'NEEDS_REVISION', 'PENDING')),
    review_comments             VARCHAR2(4000),
    review_date                 TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    status                      VARCHAR2(30) DEFAULT 'ASSIGNED' NOT NULL 
                                CONSTRAINT chk_rev_status CHECK (status IN ('ASSIGNED', 'IN_PROGRESS', 'SUBMITTED')),
    CONSTRAINT fk_rev_application FOREIGN KEY (application_id) REFERENCES APPLICATIONS(application_id) ON DELETE CASCADE,
    CONSTRAINT fk_rev_reviewer FOREIGN KEY (reviewer_id) REFERENCES USERS(user_id)
);

CREATE INDEX idx_rev_application_id ON APPLICATION_REVIEWS(application_id);
CREATE INDEX idx_rev_reviewer_id ON APPLICATION_REVIEWS(reviewer_id);
CREATE INDEX idx_rev_status ON APPLICATION_REVIEWS(status);

-- ----------------------------------------------------------------------------
-- 9. TRANSACTION TABLE: APPROVAL_WORKFLOW_LOGS
-- ----------------------------------------------------------------------------
CREATE TABLE APPROVAL_WORKFLOW_LOGS (
    log_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      NUMBER NOT NULL,
    action_by           NUMBER NOT NULL,
    previous_status     VARCHAR2(50) NOT NULL,
    new_status          VARCHAR2(50) NOT NULL,
    action_taken        VARCHAR2(50) NOT NULL,
    decision_notes      VARCHAR2(2000),
    action_timestamp    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_wf_app FOREIGN KEY (application_id) REFERENCES APPLICATIONS(application_id) ON DELETE CASCADE,
    CONSTRAINT fk_wf_actor FOREIGN KEY (action_by) REFERENCES USERS(user_id)
);

CREATE INDEX idx_wf_app_id ON APPROVAL_WORKFLOW_LOGS(application_id);
CREATE INDEX idx_wf_action_by ON APPROVAL_WORKFLOW_LOGS(action_by);
CREATE INDEX idx_wf_timestamp ON APPROVAL_WORKFLOW_LOGS(action_timestamp);

-- ----------------------------------------------------------------------------
-- 10. TRANSACTION TABLE: GRANT_DISBURSEMENTS
-- ----------------------------------------------------------------------------
CREATE TABLE GRANT_DISBURSEMENTS (
    disbursement_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id              NUMBER NOT NULL,
    tranche_number              NUMBER(2) DEFAULT 1 NOT NULL,
    disbursement_reference      VARCHAR2(50) NOT NULL CONSTRAINT uq_disb_ref UNIQUE,
    disbursement_amount         NUMBER(14,2) NOT NULL CONSTRAINT chk_disb_amt CHECK (disbursement_amount > 0),
    payment_method              VARCHAR2(50) DEFAULT 'PFMS_NEFT' NOT NULL 
                                CONSTRAINT chk_disb_method CHECK (payment_method IN ('PFMS_NEFT', 'RTGS', 'DIRECT_BENEFIT_TRANSFER', 'TREASURY_TRANSFER')),
    bank_name                   VARCHAR2(100) NOT NULL,
    account_number_masked       VARCHAR2(50) NOT NULL,
    ifsc_code                   VARCHAR2(20) NOT NULL,
    transaction_reference       VARCHAR2(100),
    scheduled_date              DATE NOT NULL,
    disbursement_date           DATE,
    status                      VARCHAR2(30) DEFAULT 'SCHEDULED' NOT NULL 
                                CONSTRAINT chk_disb_status CHECK (status IN ('SCHEDULED', 'PROCESSING', 'DISBURSED', 'FAILED', 'HOLD')),
    disbursed_by                NUMBER,
    remarks                     VARCHAR2(1000),
    created_at                  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_disb_application FOREIGN KEY (application_id) REFERENCES APPLICATIONS(application_id),
    CONSTRAINT fk_disb_officer FOREIGN KEY (disbursed_by) REFERENCES USERS(user_id)
);

CREATE INDEX idx_disb_application_id ON GRANT_DISBURSEMENTS(application_id);
CREATE INDEX idx_disb_status ON GRANT_DISBURSEMENTS(status);
CREATE INDEX idx_disb_scheduled_date ON GRANT_DISBURSEMENTS(scheduled_date);
CREATE INDEX idx_disb_disbursement_date ON GRANT_DISBURSEMENTS(disbursement_date);

-- ----------------------------------------------------------------------------
-- 11. DETAIL / TRANSACTION TABLE: UTILIZATION_REPORTS
-- ----------------------------------------------------------------------------
CREATE TABLE UTILIZATION_REPORTS (
    report_id                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id              NUMBER NOT NULL,
    tranche_number              NUMBER(2) NOT NULL,
    milestone_title             VARCHAR2(255) NOT NULL,
    amount_utilized             NUMBER(14,2) NOT NULL CONSTRAINT chk_util_amt CHECK (amount_utilized >= 0),
    utilization_percentage      NUMBER(5,2) NOT NULL CONSTRAINT chk_util_pct CHECK (utilization_percentage BETWEEN 0 AND 100),
    progress_narrative          VARCHAR2(4000) NOT NULL,
    submission_date             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    verification_status         VARCHAR2(30) DEFAULT 'PENDING_VERIFICATION' NOT NULL 
                                CONSTRAINT chk_util_verif CHECK (verification_status IN ('PENDING_VERIFICATION', 'VERIFIED_SATISFACTORY', 'AUDIT_FLAGGED', 'REJECTED')),
    verified_by                 NUMBER,
    verified_at                 TIMESTAMP,
    verification_remarks        VARCHAR2(1000),
    CONSTRAINT fk_util_app FOREIGN KEY (application_id) REFERENCES APPLICATIONS(application_id) ON DELETE CASCADE,
    CONSTRAINT fk_util_verifier FOREIGN KEY (verified_by) REFERENCES USERS(user_id)
);

CREATE INDEX idx_util_app_id ON UTILIZATION_REPORTS(application_id);
CREATE INDEX idx_util_status ON UTILIZATION_REPORTS(verification_status);

-- ----------------------------------------------------------------------------
-- 12. AUDIT TRAIL TABLE: AUDIT_LOGS
-- ----------------------------------------------------------------------------
CREATE TABLE AUDIT_LOGS (
    audit_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             NUMBER,
    entity_name         VARCHAR2(50) NOT NULL,
    entity_id           NUMBER(19),
    action              VARCHAR2(50) NOT NULL,
    details             VARCHAR2(4000),
    ip_address          VARCHAR2(50) DEFAULT '127.0.0.1',
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE SET NULL
);

CREATE INDEX idx_audit_entity ON AUDIT_LOGS(entity_name, entity_id);
CREATE INDEX idx_audit_created_at ON AUDIT_LOGS(created_at);
CREATE INDEX idx_audit_user ON AUDIT_LOGS(user_id);

